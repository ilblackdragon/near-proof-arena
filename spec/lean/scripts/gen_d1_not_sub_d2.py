#!/usr/bin/env python3
"""Emit the kernel counterexample to D1 ⊂ D2 (spec/lean/v3/NearSpecV3/Examples/D1NotSubD2*.lean).

usage: gen_d1_not_sub_d2.py CASE_DIR

CASE_DIR holds claim.bin / witness.bin of a d1run genesis-adjacent case whose claim's
`epoch_start_after` flags were zeroed (tools: docs/evidence/lean-chunk-completion/proof-debt/
d1-genesis-flag/esa_zero.py). One module per kernel decision (`D1NotSubD2K{0..3}`), plus the data
module and the corollaries (`D1NotSubD2`).
"""
import os, sys

sys.set_int_max_str_digits(0)
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "v3", "NearSpecV3", "Examples")


def lit(b):
    return "leN %d %d" % (len(b), int.from_bytes(b, "little"))


d = sys.argv[1]
cb = open(os.path.join(d, "claim.bin"), "rb").read()
wb = open(os.path.join(d, "witness.bin"), "rb").read()
name = os.path.basename(d.rstrip("/"))
open(os.path.join(out, "D1NotSubD2Data.lean"), "w").write("\n".join([
    "import NearSpecV3.D3.FunctionCall", "",
    "/-! Claim and witness of the D1 ⊄ D2 counterexample: d1run `ood/%s` (honest, nearcore `ok`) with" % name,
    "the claim's `epoch_start_after` flags set to 0. Generated by `spec/lean/scripts/gen_d1_not_sub_d2.py`. -/",
    "", "namespace NearSpecV3.Examples", "", "open NearSpec", "",
    "def claimGF : List UInt8 := " + lit(cb),
    "def witnessGF : List UInt8 := " + lit(wb), "",
    "end NearSpecV3.Examples", ""]))
decs = [("acceptsD0", "acceptsD0 claimGF witnessGF = true"),
        ("acceptsD1", "acceptsD1 claimGF witnessGF = true"),
        ("acceptsD2", "acceptsD2 claimGF witnessGF = false"),
        ("acceptsD3", "D3.acceptsD3 claimGF witnessGF = false")]
for i, (n, st) in enumerate(decs):
    open(os.path.join(out, "D1NotSubD2K%d.lean" % i), "w").write("\n".join([
        "import NearSpecV3.Examples.D1NotSubD2Data", "",
        "/-! One kernel decision of the D1 ⊄ D2 counterexample (`D1NotSubD2`). -/", "",
        "namespace NearSpecV3.Examples", "", "open NearSpec NearSpecV3", "",
        "set_option maxRecDepth 200000 in",
        "theorem gf_%s : %s := by decide +kernel" % (n, st), "",
        "end NearSpecV3.Examples", ""]))
