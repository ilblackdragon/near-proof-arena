#!/usr/bin/env python3
"""Emit the ML-DSA-65 pin data for `spec/lean/v3/NearSpecV3/Examples/MlDsaVectors.lean`.

Two sources, neither involving Lean:

* NIST ACVP `ML-DSA-sigVer-FIPS204/internalProjection.json` (usnistgov/ACVP-Server, gen-val/json-files):
  every ML-DSA-65 test of the pure external interface (with a context string), the internal
  interface, and the internal interface with an external mu. Pre-hash groups are skipped (nearcore
  verifies pure ML-DSA).
* `near-arena-oracle-v3-successor mldsa-vectors` (oracle/v3-successor/src/mldsa_vectors.rs): the
  pinned crate's verdicts (`near_crypto::Signature::verify`, aws-lc-rs 1.16.2) on 32-byte messages
  with an empty context, including malformed hint encodings.

usage: mldsa_vectors_to_lean.py --acvp internalProjection.json --crate crate-vectors.json --out DIR
writes DIR/MlDsaAcvp.lean and DIR/MlDsaCrate.lean.
"""
import argparse
import hashlib
import json
from pathlib import Path


def acvp_rows(path):
    d = json.loads(Path(path).read_text())
    rows = []
    for g in d["testGroups"]:
        if g["parameterSet"] != "ML-DSA-65":
            continue
        if g["signatureInterface"] == "external" and g["preHash"] != "pure":
            continue
        kind = "ext" if g["signatureInterface"] == "external" else ("mu" if g["externalMu"] else "int")
        for t in g["tests"]:
            rows.append((kind, t["tcId"], bool(t["testPassed"]), t["pk"].lower(), (t.get("message") or "").lower(),
                         (t.get("context") or "").lower(), (t.get("mu") or "").lower(), t["signature"].lower()))
    return rows


def emit_acvp(rows, src_sha, out):
    L = ["import NearSpecV3.MlDsa65", "",
         "/-! NIST ACVP `ML-DSA-sigVer-FIPS204` vectors, ML-DSA-65 groups 3 (external, pure, with a context),",
         "9 (internal, external μ) and 10 (internal): every test of those groups. Source",
         "`usnistgov/ACVP-Server` `gen-val/json-files/ML-DSA-sigVer-FIPS204/internalProjection.json`,",
         f"sha256 `{src_sha}`. Generated by `tools/d3/mldsa_vectors_to_lean.py`; do not edit. -/", "",
         "namespace NearSpecV3.Examples.MlDsaAcvp", "",
         "/-- `(kind, tcId, testPassed, pk, message, context, mu, signature)`, hex; kind `ext` / `mu` / `int`. -/",
         "def vectors : Array (String × Nat × Bool × String × String × String × String × String) := #["]
    for i, (kind, tc, ok, pk, msg, ctx, mu, sig) in enumerate(rows):
        sep = "," if i + 1 < len(rows) else ""
        L.append(f'  ("{kind}", {tc}, {"true" if ok else "false"},\n   "{pk}",\n   "{msg}",\n   "{ctx}",\n   "{mu}",\n   "{sig}"){sep}')
    L += ["]", "", "end NearSpecV3.Examples.MlDsaAcvp", ""]
    Path(out).write_text("\n".join(L))


def emit_crate(d, src_sha, out):
    L = ["import NearSpecV3.MlDsa65", "",
         "/-! The pinned crate's ML-DSA-65 verdicts: `near_crypto::Signature::verify` (aws-lc-rs 1.16.2, pure,",
         "empty context) on 32-byte messages, from `near-arena-oracle-v3-successor mldsa-vectors`",
         f"(`oracle/v3-successor/src/mldsa_vectors.rs`), output sha256 `{src_sha}`. A case is a base",
         "signature with byte patches `(offset, value)`. Generated by `tools/d3/mldsa_vectors_to_lean.py`;",
         "do not edit. -/", "",
         "namespace NearSpecV3.Examples.MlDsaCrate", "",
         "def keys : Array String := #[" + ",".join(f'\n  "{k}"' for k in d["keys"]) + "]", "",
         "def sigs : Array String := #[" + ",".join(f'\n  "{s}"' for s in d["sigs"]) + "]", "",
         "/-- `(name, key index, message hex, signature index, patch, nearcore verdict)`. -/",
         "def cases : Array (String × Nat × String × Nat × List (Nat × Nat) × Bool) := #["]
    cs = d["cases"]
    for i, c in enumerate(cs):
        sep = "," if i + 1 < len(cs) else ""
        patch = "[" + ", ".join(f"({o}, {b})" for o, b in c["patch"]) + "]"
        L.append(f'  ("{c["name"]}", {c["key"]}, "{c["msg"]}", {c["sig"]}, {patch}, {"true" if c["expect"] else "false"}){sep}')
    L += ["]", "", "end NearSpecV3.Examples.MlDsaCrate", ""]
    Path(out).write_text("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--acvp", required=True)
    ap.add_argument("--crate", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out)
    rows = acvp_rows(a.acvp)
    emit_acvp(rows, hashlib.sha256(Path(a.acvp).read_bytes()).hexdigest(), out / "MlDsaAcvp.lean")
    d = json.loads(Path(a.crate).read_text())
    emit_crate(d, hashlib.sha256(Path(a.crate).read_bytes()).hexdigest(), out / "MlDsaCrate.lean")
    print(f"acvp {len(rows)} vectors ({sum(r[2] for r in rows)} accept); crate {len(d['cases'])} cases "
          f"({sum(c['expect'] for c in d['cases'])} accept)")


if __name__ == "__main__":
    main()
