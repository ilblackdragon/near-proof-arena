#!/usr/bin/env python3
"""L0 exercise map and per-row breakage controls, on the control build of the successor checker.

The control build is `nearspec-v3-ctl-successor`, generated by `tools/d3/l0_ctl_patch.py` in a copy
of the tree (never on the default path). Subcommands:

* `trace`    run it with `NEARSPEC_TRACE=1` over a case list; per case, the verdict and the host
             arms / action tags that fired (observation only). Output: JSONL.
* `identity` compare the verdicts of the control build (trace on, no ablation) with the default
             checker's verdicts (a replay `results.jsonl`, e.g. the pre-freeze or freeze replay):
             every case must have the same verdict and reason.
* `map`      per coverage row, the exercising cases with their nearcore verdict (meta.json
             `expected_rel`, cold pinned nearcore).
* `ablate`   per row, a nearcore-judged replay (`replay_successor.replay`, the repository's own
             comparator) of up to K exercising cases with `NEARSPEC_ABLATE=<target>`; the control
             detects the breakage iff that replay has a disagreement. The same cases replayed
             without ablation must have none (the baseline run of the same command).

No subcommand changes a checker verdict; the ablation environment variable exists only in the
control build.
"""
import argparse
import collections
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import replay_successor as rs  # noqa: E402

TIER = "allFeatures"


def _trace_batch(binary, cases, timeout):
    env = dict(os.environ, NEARSPEC_TRACE="1")
    env.pop("NEARSPEC_ABLATE", None)
    p = subprocess.run([str(binary), "--tier", TIER, *cases], capture_output=True, text=True,
                       timeout=timeout, env=env, check=True)
    rows = rs.parse_rows(p.stdout, cases, TIER)
    ev = {}
    cur = None
    for line in p.stderr.splitlines():
        if line.startswith("CASE "):
            cur = str(Path(line[5:]).resolve())
            ev[cur] = {"hosts": collections.Counter(), "acts": collections.Counter()}
        elif line.startswith("H ") and cur:
            ev[cur]["hosts"][line[2:]] += 1
        elif line.startswith("A ") and cur:
            ev[cur]["acts"][line[2:]] += 1
    if set(ev) != set(rows):
        raise ValueError("trace markers do not match the result rows")
    return [{"case": c, "verdict": r["verdict"], "reason": r["reason"],
             "hosts": dict(ev[c]["hosts"]), "acts": dict(ev[c]["acts"])} for c, r in rows.items()]


def cmd_trace(a):
    cases = [str(Path(l).resolve()) for l in a.cases_file.read_text().splitlines() if l]
    done = set()
    if a.out.exists():
        done = {json.loads(l)["case"] for l in a.out.read_text().splitlines() if l}
    todo = [c for c in cases if c not in done]
    batches = [todo[i:i + a.batch] for i in range(0, len(todo), a.batch)]
    with open(a.out, "a") as f, ThreadPoolExecutor(max_workers=a.jobs) as ex:
        for n, rows in enumerate(ex.map(lambda b: _trace_batch(a.binary, b, a.timeout), batches)):
            for r in rows:
                f.write(json.dumps(r, sort_keys=True) + "\n")
            f.flush()
            if n % 20 == 0:
                print(f"{n + 1}/{len(batches)} batches", file=sys.stderr, flush=True)


def load_jsonl(p):
    return [json.loads(l) for l in Path(p).read_text().splitlines() if l]


def cmd_identity(a):
    ref = {}
    for p in a.reference:
        for r in load_jsonl(p):
            ref[str(Path(r["case"]).resolve())] = (r["verdict"], r["reason"])
    tr = load_jsonl(a.trace)
    same = diff = missing = 0
    bad = []
    for r in tr:
        x = ref.get(r["case"])
        if x is None:
            missing += 1
        elif x == (r["verdict"], r["reason"]):
            same += 1
        else:
            diff += 1
            bad.append((r["case"], x, (r["verdict"], r["reason"])))
    out = {"traced": len(tr), "compared": same + diff, "identical": same, "different": diff,
           "no_reference": missing, "examples": bad[:20]}
    print(json.dumps(out, indent=2))
    return 1 if diff else 0


def expected(case):
    m = json.loads((Path(case) / "meta.json").read_text())
    return m.get("expected_rel")


def cmd_map(a):
    rows = collections.defaultdict(lambda: {"accept": [], "reject": []})
    for p in a.trace:
        for r in load_jsonl(p):
            e = expected(r["case"])
            if type(e) is not bool:
                continue
            k = "accept" if e else "reject"
            # positive evidence only from cases the default verdict also judges (accept/reject)
            if r["verdict"] == "out_of_domain":
                continue
            for h in r["hosts"]:
                rows["host:" + h][k].append(r["case"])
            for t in r["acts"]:
                rows["act:" + t][k].append(r["case"])
    out = {k: {"accept": sorted(set(v["accept"])), "reject": sorted(set(v["reject"]))}
           for k, v in sorted(rows.items())}
    a.out.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    for k, v in out.items():
        print(f"{k:60s} nearcore-accept {len(v['accept']):6d}  nearcore-reject {len(v['reject']):6d}")


def pick(cases, k):
    """Up to k cases, spread over the families (corpus directory / fixture family)."""
    by = collections.defaultdict(list)
    for c in cases:
        by[str(Path(c).parent)].append(c)
    out = []
    groups = [sorted(v) for _, v in sorted(by.items())]
    i = 0
    while len(out) < k and any(groups):
        g = groups[i % len(groups)]
        if g:
            out.append(g.pop(0))
        i += 1
        groups = [g for g in groups if g] or groups
        if not any(groups):
            break
    return out


def run_replay(binary, cases, out, ablate, jobs):
    env_old = os.environ.pop("NEARSPEC_ABLATE", None)
    if ablate:
        os.environ["NEARSPEC_ABLATE"] = ablate
    try:
        try:
            rep = rs.replay(binary, TIER, cases, out, batch=10, timeout=1800, jobs=jobs)
        except Exception as e:  # a replay failure is recorded, never treated as detection
            return {"status": "error", "detail": str(e)}
        return {"status": rep["status"], "disagreements": len(rep.get("disagreements", [])),
                "verdicts": rep.get("verdicts"),
                "flipped": [d[0] for d in rep.get("disagreements", [])][:10],
                "binary_sha256": rep["package"]["sha256"], "report": str(Path(out) / "report.json")}
    finally:
        os.environ.pop("NEARSPEC_ABLATE", None)
        if env_old is not None:
            os.environ["NEARSPEC_ABLATE"] = env_old


def cmd_ablate(a):
    m = json.loads(a.map.read_text())
    targets = [t for t in (a.targets or m) if t in m or t.startswith("guard:")]
    res = json.loads(a.out.read_text()) if a.out.exists() else {}
    work = a.workdir
    for t in targets:
        if t in res and not a.force:
            continue
        ent = m.get(t, {"accept": [], "reject": []})
        cases = pick(ent["accept"], a.k) + pick(ent["reject"], a.k_reject)
        if not cases:
            res[t] = {"cases": 0}
            continue
        safe = t.replace(":", "_").replace("/", "_").replace(" ", "_")[:80]
        base = run_replay(a.binary, cases, work / safe / "baseline", None, a.jobs)
        abl = run_replay(a.binary, cases, work / safe / "ablated", t, a.jobs)
        res[t] = {"cases": len(cases), "case_list": cases, "baseline": base, "ablated": abl,
                  "detected": base.get("status") == "pass" and abl.get("disagreements", 0) > 0}
        a.out.write_text(json.dumps(res, indent=1, sort_keys=True) + "\n")
        print(f"{t:60s} cases {len(cases):3d} baseline {base.get('status')} "
              f"ablated-disagreements {abl.get('disagreements')}", flush=True)
    a.out.write_text(json.dumps(res, indent=1, sort_keys=True) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    t = sp.add_parser("trace")
    t.add_argument("--binary", type=Path, required=True)
    t.add_argument("--cases-file", type=Path, required=True)
    t.add_argument("--out", type=Path, required=True)
    t.add_argument("--jobs", type=int, default=4)
    t.add_argument("--batch", type=int, default=50)
    t.add_argument("--timeout", type=float, default=3600)
    i = sp.add_parser("identity")
    i.add_argument("--trace", type=Path, required=True)
    i.add_argument("--reference", type=Path, nargs="+", required=True)
    m = sp.add_parser("map")
    m.add_argument("--trace", type=Path, nargs="+", required=True)
    m.add_argument("--out", type=Path, required=True)
    b = sp.add_parser("ablate")
    b.add_argument("--binary", type=Path, required=True)
    b.add_argument("--map", type=Path, required=True)
    b.add_argument("--out", type=Path, required=True)
    b.add_argument("--workdir", type=Path, required=True)
    b.add_argument("--targets", nargs="*")
    b.add_argument("--k", type=int, default=12, help="nearcore-accepted exercising cases per row")
    b.add_argument("--k-reject", type=int, default=4, help="nearcore-rejected exercising cases per row")
    b.add_argument("--jobs", type=int, default=4)
    b.add_argument("--force", action="store_true")
    a = ap.parse_args()
    return {"trace": cmd_trace, "identity": cmd_identity, "map": cmd_map, "ablate": cmd_ablate}[a.cmd](a) or 0


if __name__ == "__main__":
    sys.exit(main())
