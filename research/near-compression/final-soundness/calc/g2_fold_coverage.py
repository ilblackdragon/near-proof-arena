#!/usr/bin/env python3
"""Generate the full FINAL-round and O-2 parent-round scalar fold transfers.

`g2_fold_certificates.py` selects only the measured FINAL's sub-codes 1..k of each round.
This selects *every* O-2 sub-code of every measured FINAL round and of the O-2 PARENT rounds:

  * FINAL, all four rounds (k1 = 1, then k = 4, 4, 4), sub-codes s = 0..k;
  * PARENT (the measured inner layer), the O-2 rounds r1 and r2, s = 0..k.

Rounds whose regime is Johnson (PARENT r0/r3 in the G2 trace) have no O-2 certificate and are
deliberately absent; they need the DKTGlue Johnson route.

Two modes, mirroring `g2_fold_certificates.py`:

* `certs`     -> `DKTG2FoldCoverageCerts`, only the certificates NOT already carried by
                 `DKTG2FoldCerts` (the sub-code-0 ones and all of PARENT).
                 `DKTG2FoldCerts` is imported and its 13 proofs are reused.
* `transfers` -> `DKTG2FoldCoverage`, 27 transfers.  Reused sub-codes call
                 `DKTG2FoldCerts.mca{i}`; fresh ones call `DKTG2FoldCoverageCerts.mca{j}`.

The result is still a table of *independent scalar folds*; adaptive composition is added
separately by `DKTAdaptive`.  No WHIR or QROM bound is asserted.
"""
import re
import sys
from pathlib import Path

from audit_g2 import audit, FORMAL

ROUND_FOLD = {'final': {0: 1, 1: 4, 2: 4, 3: 4}, 'parent': {0: 2, 1: 4, 2: 4, 3: 4}}
# The 13 sub-codes DKTG2FoldTransfer already carries, in its certificate index order.
LEGACY = ['final r0 s1', 'final r1 s1', 'final r1 s2', 'final r1 s3', 'final r1 s4',
          'final r2 s1', 'final r2 s2', 'final r2 s3', 'final r2 s4',
          'final r3 s1', 'final r3 s2', 'final r3 s3', 'final r3 s4']


def selected():
    report = audit()
    if not report['artifact_checks_pass']:
        raise ValueError(report['failures'])
    for role in ('final', 'parent'):
        for r, row in enumerate(report['rounds'][role]):
            if row['fold'] != ROUND_FOLD[role][r]:
                raise ValueError(('fold mismatch', role, r))
    sources = [(p, p.read_text()) for p in sorted((FORMAL / 'lean').glob('DKTCertsO2_[0-7].lean'))]
    result = []
    for role in ('final', 'parent'):
        for r, row in enumerate(report['rounds'][role]):
            if not row['first_order']:
                continue
            fold = ROUND_FOLD[role][r]
            for s in range(0, fold + 1):
                key = row['subcodes'][s]['key']
                matches = []
                for path, source in sources:
                    m = re.search(r'^-- ' + re.escape(key) + r' .*\ndef prof(\d+)', source, re.M)
                    if not m:
                        continue
                    end = re.search(r'^-- \d+,\d+,\d+,\d+  |^end DKTCerts', source[m.end():], re.M)
                    block = source[m.start(): m.end() + end.start()]
                    budget = re.search(r'\(exceptional.card : ℚ\) ≤ (\d+) ∧', block)[1]
                    matches.append((path.name, block, budget))
                if len(matches) != 1:
                    raise ValueError((key, len(matches)))
                path, block, budget = matches[0]
                n, k, a, _ = map(int, key.split(','))
                parent_a = (row['agreement'] + 2 ** s - 1) // 2 ** s
                tag = f'{role} r{r} s{s}'
                result.append(dict(key=key, source=path, block=block, budget=budget, role=role,
                                   r=r, s=s, n=n, k=k, a=a, parent_a=parent_a,
                                   legacy=LEGACY.index(tag) if tag in LEGACY else None))
    return result


def preamble():
    """The three imports, four `open`s and the two `set_option`s, without any helper body."""
    source = (FORMAL / 'lean/DKTCertsO2_5.lean').read_text()
    end = re.search(r'^namespace DKTCerts\b', source, re.M).start()
    return source[source.index('import '):end]


def emit_certs(rows):
    fresh = [r for r in rows if r['legacy'] is None]
    print('/- Generated by calc/g2_fold_coverage.py certs.\n'
          '   Kernel proof bodies for the O-2 sub-codes NOT already carried by DKTG2FoldCerts:\n'
          '   sub-code s = 0 of every measured FINAL round, and all of PARENT r1, r2.\n'
          '   DKTG2FoldCerts is imported and its 13 proofs are reused unchanged. -/')
    print('import DKTG2FoldCerts')
    print('\n'.join(ln for ln in preamble().splitlines()
                    if ln.strip() and not ln.startswith('import ')))
    print('\nopen DKTG2FoldCerts (p envAt listQ sumTo sum_range_eq_sumTo opt_le_envAt')
    print('  listEnvelope_eq mca_of list_of)\n')
    print('namespace DKTG2FoldCoverageCerts\n')
    for row in fresh:
        block = re.sub(r'\b(prof|dim|slots|rows|hs|verified|envelope|mca|listq|list)\d+\b',
                       lambda m: m[1] + str(fresh.index(row)), row['block'])
        print('/- Source: ' + row['source'] + '; key ' + row['key'] + ' -/')
        print(block)
    print('end DKTG2FoldCoverageCerts')
    for i in range(len(fresh)):
        print(f'#print axioms DKTG2FoldCoverageCerts.mca{i}')


def emit_transfers(rows):
    print('import DKTWhirFold\nimport DKTG2FoldCerts\nimport DKTG2FoldCoverageCerts\n')
    print('/- Generated by calc/g2_fold_coverage.py transfers.\n'
          '   Every O-2 sub-code of every measured FINAL round and of the PARENT O-2 rounds.\n'
          '   Independent scalar folds: the adaptive composition is in DKTAdaptive and\n'
          '   DKTRoundCompose; Johnson rounds are absent and need DKTGlue. No WHIR bound. -/')
    print('namespace DKTG2FoldCoverage\nopen Polynomial ReedSolomon DKTWhirFold\n'
          'set_option maxRecDepth 100000\nset_option exponentiation.threshold 1000\n'
          'variable {F E : Type} [Field F] [NeZero (2 : F)] [Field E] [IsAlgClosed E]\n')
    fresh_index = {id(r): i for i, r in enumerate(r for r in rows if r['legacy'] is None)}
    for row in rows:
        n, k, a, b = row['n'], row['k'], row['a'], row['budget']
        name = f"{row['role']}_r{row['r']}_s{row['s']}"
        if row['legacy'] is None:
            src = f'DKTG2FoldCoverageCerts.mca{fresh_index[id(row)]}'
        else:
            src = f'DKTG2FoldCerts.mca{row["legacy"]}'
        print(f'''open Classical in
/-- {row['role'].upper()} r{row['r']}, subfold {row['s']}; certificate {row['key']}. -/
theorem {name} (hF : ringChar F = 2013265921)
    (domain : SquarePairedDomain F {n})
    (word : Fin {n} × Fin 2 → F) (iota : F →+* E) :
    ∃ exceptional : Finset F, (exceptional.card : ℚ) ≤ {b} ∧
      ∀ gamma ∉ exceptional, ∀ P : F[X], P.degree < {k} →
        {a} ≤ (polynomialAgreementSet domain.child (backendFold domain word gamma) P).card →
        ∃ parent : F[X], parent.natDegree < {2 * k} ∧
          P = FoldingPolynomial.polyFold parent 2 gamma ∧
          {row['parent_a']} ≤ (pairedPolynomialAgreementSet domain word parent).card := by
  obtain ⟨ex, hcard, hgood⟩ := {src} hF domain.child
    (binarySplitWord domain word) iota
  refine ⟨ex, hcard, ?_⟩
  intro gamma hg P hP hA
  rw [backendFold_eq] at hA
  exact exists_parentPolynomial_of_exactAgreement domain word (by decide)
    (by decide : {row['parent_a']} ≤ 2 * {a}) gamma P hA (hgood gamma hg P hP hA)
''')
    print('/-- Sum of all coverage scalar exceptional-count bounds. -/')
    print('def coverageFoldBudget : ℕ := ' + ' + '.join(r['budget'] for r in rows))
    print(f'theorem coverageFoldBudget_sum : coverageFoldBudget = '
          f'{sum(int(r["budget"]) for r in rows)} := by decide')
    print('end DKTG2FoldCoverage')
    for row in rows:
        print(f"#print axioms DKTG2FoldCoverage.{row['role']}_r{row['r']}_s{row['s']}")
    print('#print axioms DKTG2FoldCoverage.coverageFoldBudget_sum')


if __name__ == '__main__':
    kind = sys.argv[1] if len(sys.argv) > 1 else 'transfers'
    {'certs': emit_certs, 'transfers': emit_transfers}[kind](selected())
