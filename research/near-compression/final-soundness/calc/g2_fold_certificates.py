#!/usr/bin/env python3
"""Select existing kernel certificates and generate measured FINAL fold transfers.

Run with `certs` or `transfers`; output goes to stdout. Inputs are the recorded
G2 VK rows plus existing DKTCertsO2 source proofs, not freshly trusted numbers.
Each generated transfer is one scalar binary fold, not the complete WHIR game.
"""
import argparse
import re
from pathlib import Path
from audit_g2 import audit, FORMAL


def selected():
    report = audit()
    if not report['artifact_checks_pass']:
        raise ValueError(report['failures'])
    sources = [(p, p.read_text()) for p in sorted((FORMAL/'lean').glob('DKTCertsO2_[0-7].lean'))]
    result = []
    for r, row in enumerate(report['rounds']['final']):
        for s, sub in enumerate(row['subcodes'][1:], 1):
            key = sub['key']
            found = []
            for path, source in sources:
                m = re.search(r'^-- ' + re.escape(key) + r' .*\ndef prof(\d+)', source, re.M)
                if m:
                    end = re.search(r'^-- \d+,\d+,\d+,\d+  |^end DKTCerts', source[m.end():], re.M)
                    block = source[m.start(): m.end()+end.start()]
                    old = m[1]
                    new = str(len(result))
                    block = re.sub(r'\b(prof|dim|slots|rows|hs|verified|envelope|mca|listq|list)'+old+r'\b',
                                   lambda m: m[1]+new, block)
                    budget = re.search(r'\(exceptional.card : ℚ\) ≤ (\d+) ∧', block)[1]
                    found.append((path.name, block, budget))
            if len(found) != 1:
                raise ValueError((key, len(found)))
            path, block, budget = found[0]
            n, k, a, _ = map(int, key.split(','))
            parent_a = (row['agreement'] + 2**(s-1)-1)//2**(s-1)
            result.append(dict(key=key, source=path, block=block, budget=budget,
                               r=r, s=s, n=n, k=k, a=a, parent_a=parent_a))
    return result


def certificate_file(rows):
    source=(FORMAL/'lean/DKTCertsO2_5.lean').read_text()
    first=re.search(r'^-- \d+,\d+,\d+,\d+  ',source,re.M).start()
    header=source[source.index('import '):first].replace('namespace DKTCerts','namespace DKTG2FoldCerts')
    print('/- Generated by calc/g2_fold_certificates.py certs.\n'
          '   Existing kernel proof bodies for the 13 measured FINAL binary subfolds. -/')
    print(header)
    for row in rows:
        print('/- Source: '+row['source']+'; key '+row['key']+' -/')
        print(row['block'])
    print('end DKTG2FoldCerts')
    for i in range(len(rows)):
        print(f'#print axioms DKTG2FoldCerts.mca{i}')


def transfer_file(rows):
    print('import DKTWhirFold\nimport DKTG2FoldCerts\n')
    print('/- Generated by calc/g2_fold_certificates.py transfers.\n'
          '   Separate scalar folds: no adaptive composition or total WHIR bound is asserted. -/')
    print('namespace DKTG2FoldTransfer\nopen Polynomial ReedSolomon DKTWhirFold\n'
          'set_option maxRecDepth 100000\nset_option exponentiation.threshold 1000\n'
          'variable {F E : Type} [Field F] [NeZero (2 : F)] [Field E] [IsAlgClosed E]\n')
    for i,row in enumerate(rows):
        n,k,a,b=row['n'],row['k'],row['a'],row['budget']
        name=f"final_r{row['r']}_s{row['s']}"
        print(f'''open Classical in
/-- Measured FINAL r{row['r']}, subfold {row['s']}; certificate {row['key']}. -/
theorem {name} (hF : ringChar F = 2013265921)
    (domain : SquarePairedDomain F {n})
    (word : Fin {n} × Fin 2 → F) (iota : F →+* E) :
    ∃ exceptional : Finset F, (exceptional.card : ℚ) ≤ {b} ∧
      ∀ gamma ∉ exceptional, ∀ P : F[X], P.degree < {k} →
        {a} ≤ (polynomialAgreementSet domain.child (backendFold domain word gamma) P).card →
        ∃ parent : F[X], parent.natDegree < {2*k} ∧
          P = FoldingPolynomial.polyFold parent 2 gamma ∧
          {row['parent_a']} ≤ (pairedPolynomialAgreementSet domain word parent).card := by
  obtain ⟨ex, hcard, hgood⟩ := DKTG2FoldCerts.mca{i} hF domain.child
    (binarySplitWord domain word) iota
  refine ⟨ex, hcard, ?_⟩
  intro gamma hg P hP hA
  rw [backendFold_eq] at hA
  exact exists_parentPolynomial_of_exactAgreement domain word (by decide)
    (by decide : {row['parent_a']} ≤ 2 * {a}) gamma P hA (hgood gamma hg P hP hA)
''')
    budgets = [int(row['budget']) for row in rows]
    print('/-- Sum of the 13 rounded scalar exceptional-count bounds. -/')
    print('def finalScalarFoldBudget : ℕ := ' + ' + '.join(map(str, budgets)))
    print(f'''theorem finalScalarFoldBudget_sum : finalScalarFoldBudget = {sum(budgets)} := by decide

/-- Exact arithmetic only: these scalar budgets, divided by the Ext12 field
cardinality, total less than 2^-283. Other WHIR moves and QROM losses are absent. -/
theorem finalScalarFoldBudget_fraction_lt :
    (finalScalarFoldBudget : ℚ) / (2013265921 : ℚ)^12 < 1 / (2 : ℚ)^283 := by
  norm_num [finalScalarFoldBudget]
''')
    print('end DKTG2FoldTransfer')
    for row in rows:
        print(f"#print axioms DKTG2FoldTransfer.final_r{row['r']}_s{row['s']}")
    print('#print axioms DKTG2FoldTransfer.finalScalarFoldBudget_fraction_lt')


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('kind', choices=['certs','transfers'])
    args=parser.parse_args()
    (certificate_file if args.kind=='certs' else transfer_file)(selected())
