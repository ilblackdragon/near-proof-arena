#!/usr/bin/env python3
"""Generate WasmBase/Main/SegSoundCMP.lean: the multiproof-AIR instances (`foo_mp`) of `HoldsXS`
theorems `fooS` in Main/SegS/*.lean — the statement with `HoldsX (wasmBaseSegAirMP …)` /
`ChipIf … (wasmBaseSegAirMP …)`, proved by `fooS … H.toSMP (SegSha.ChipIf.toSMP H hC) …`.
  python3 gen/segS/gen_mp.py $PWD
"""
import re, sys, os

ROOT = sys.argv[1]
TARGETS = [("SegTomb", "seg_tombDeadS", "seg_tombDead_mp"), ("SegHalt", "seg_sound_haltS", "seg_sound_halt_mp"),
           ("SegSoundC", "seg_sound_cS", "seg_sound_c_mp"), ("SegSoundC", "seg_sound_anyS", "seg_sound_any_mp")]


def statement(src, name):
    i = src.index(f"theorem {name} ")
    j = src.index(":= by", i)
    return src[i:j].rstrip()


def explicit_binders(sig):
    # top-level `( name : … )` binders before the final colon
    out, depth, k = [], 0, 0
    while k < len(sig):
        ch = sig[k]
        if ch in "({[⦃":
            if depth == 0 and ch == "(":
                m = re.match(r"\(\s*([A-Za-z_][A-Za-z0-9_']*(?:\s+[A-Za-z_][A-Za-z0-9_']*)*)\s*:", sig[k:])
                if m:
                    out.extend(m.group(1).split())
            depth += 1
        elif ch in ")}]⦄":
            depth -= 1
        elif ch == ":" and depth == 0:
            break
        k += 1
    return out


out = ["import WasmBase.Main.SegSoundMP", "import WasmBase.Main.SegS.SegSoundC",
       "/-!\n# WasmBase.Main.SegSoundCMP — CORE's segment theorems for the multiproof AIR (E2E M4c, MP)\n\n"
       "`seg_tombDead_mp`, `seg_sound_halt_mp`, **`seg_sound_c_mp`**, **`seg_sound_any_mp`**: the statements of "
       "CORE's `seg_tombDead`, `seg_sound_halt`, `seg_sound_c`, `seg_sound_any` with "
       "`HoldsX (wasmBaseSegAirMP …)` and `ChipIf compressW (wasmBaseSegAirMP …)`; each is its `HoldsXS` version "
       "(`Main/SegS/*.lean`) applied to `HoldsX.toSMP` / `SegSha.ChipIf.toSMP`.  Generated by "
       "`gen/segS/gen_mp.py`.\n-/",
       "namespace WasmBase\n", "open ZkFormal.Algebra Chips Seg Local", "open NearSpecV3.Wasm hiding P",
       "set_option linter.unusedSimpArgs false", "set_option maxRecDepth 100000\n"]
for mod, sname, mname in TARGETS:
    src = open(os.path.join(ROOT, f"WasmBase/Main/SegS/{mod}.lean")).read()
    sig = statement(src, sname)
    head = sig[len(f"theorem {sname} "):]
    names = explicit_binders(head)
    hasC = "ChipIfS" in head
    head = head.replace("(H : HoldsXS nloc ngl pub tr)", "(H : HoldsX (wasmBaseSegAirMP nloc ngl) pub tr)")
    head = head.replace("SegSha.ChipIfS SegSha.compressW nloc ngl pub tr chip",
                        "SegSha.ChipIf SegSha.compressW (wasmBaseSegAirMP nloc ngl) pub tr chip")
    assert "HoldsXS" not in head and "ChipIfS" not in head, head
    args = []
    for n in names:
        args.append({"H": "H.toSMP", "hC": "(SegSha.ChipIf.toSMP H hC)"}.get(n, n))
    out.append(f"/-- `{sname}` for the multiproof AIR `wasmBaseSegAirMP`. -/")
    out.append(f"theorem {mname} {head} :=\n  {sname} {' '.join(args)}\n")
for _, _, mname in TARGETS:
    out.append(f"#print axioms {mname}")
out.append("\nend WasmBase\n")
open(os.path.join(ROOT, "WasmBase/Main/SegSoundCMP.lean"), "w").write("\n".join(out))
print("ok")
