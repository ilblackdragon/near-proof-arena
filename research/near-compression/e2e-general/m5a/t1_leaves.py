#!/usr/bin/env python3
"""B-T2: dump a case's working-set leaves (INTAKE and after the writes) as a Lean data module.

  t1_leaves.py STATE.json NAMES.json OUT.lean SEG_STATEMENT.json [NAMESPACE]

Runs the trace generator's working-set construction (`tracegen.Gen.build_ws`, split mode) and
writes the leaves `(kd, pre, cur, wr)` in the circuit's leaf order (`Gen.keys`), the tree depth and
the depth-24 roots `R_in` / `R_out` the segment proof publishes (`root_a`, `root_b` of `stats.json`).
`StateM5a/T1Ws.lean` recomputes both roots from these leaves in the kernel with the state view's
own `wsRoot` (lane B's `StateView`, depth 24): an independent cross-check of the generator's tree
and the non-vacuity witness of `StHalfC.WsMoves` on T1.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tracegen  # noqa: E402

CAP = {}
orig = tracegen.Gen.build_ws


def build_ws(self):
    CAP['keys'] = list(self.keys)
    CAP['pre'] = {k: self.pre[k] for k in self.keys}
    CAP['final'] = dict(self.final)
    CAP['D'] = self.D
    return orig(self)


tracegen.Gen.build_ws = build_ws


def hx(b):
    return bytes(b).hex()


def blit(v):
    """A byte-list literal (long hex strings make the kernel's `ofHex?` recurse too deep)."""
    return '[' + ', '.join(str(b) for b in bytes.fromhex(v)) + ']'


def root21(v):
    """18 public limbs (21 bits, 3 per 64-bit word) as the 48 big-endian root bytes."""
    return b''.join((v[3 * i] + (v[3 * i + 1] << 21) + (v[3 * i + 2] << 42)).to_bytes(8, 'big') for i in range(6))


def lit(b):
    """A byte-list literal (the kernel evaluates `ofHex?` on strings slowly and deeply)."""
    return '[' + ', '.join(str(x) for x in bytes(b)) + ']'


def ref(p):
    return '⟨%s, %d, %s⟩' % ('true' if p[0] else 'false', p[1], lit(p[2]))


def main():
    st = json.load(open(sys.argv[1]))
    names = json.load(open(sys.argv[2]))
    out = sys.argv[3]
    segst = json.load(open(sys.argv[4]))['statement']
    ns = sys.argv[5] if len(sys.argv) > 5 else 'StateM5a.T1WsData'
    g = tracegen.make_gen(st, names, None, None, 1, 0, True, False)
    plan = g.make_plan()
    tracegen.PT.OVERRIDE.clear()
    g = tracegen.make_gen(st, names, None, plan, 1, 0, True, False)
    import tempfile
    with tempfile.TemporaryDirectory(dir=os.environ.get('TMPDIR')) as d:
        g.write_split(d, None, stats_only=True)
    keys, pre, fin, D = CAP['keys'], CAP['pre'], CAP['final'], CAP['D']
    l0, l1 = [], []
    for k in keys:
        kd = tracegen.sha(k)
        l0.append('⟨%s, %s, %s, false⟩' % (lit(kd), ref(pre[k]), ref(pre[k])))
        if k in fin:
            l1.append('⟨%s, %s, %s, true⟩' % (lit(kd), ref(pre[k]), ref(fin[k])))
        else:
            l1.append('⟨%s, %s, %s, false⟩' % (lit(kd), ref(pre[k]), ref(pre[k])))
    seg = g.seg_stats if hasattr(g, 'seg_stats') else None
    lines = ['import StateM5a.StateView', '',
             '/-! Generated by `m5a/t1_leaves.py` from `%s` (do not edit). -/' % os.path.basename(
                 os.path.dirname(st.get('case', '')) + '/' + os.path.basename(st.get('case', ''))), '',
             'namespace %s' % ns, '', 'open StateM5a.StateView', '',
             'def h (s : String) : ArenaCore.Bytes := (ArenaCore.Bytes.ofHex? s).getD []', '',
             'def depthD : Nat := %d' % D, '',
             'def keys : List ArenaCore.Bytes := [%s]' % ', '.join(lit(k) for k in keys), '',
             '/-- The roots the generator computed (`stats.json` `root_a` / `root_b`), as bytes. -/',
             'def rootA : ArenaCore.Bytes := %s' % lit(root21(segst[17:35])),
             'def rootB : ArenaCore.Bytes := %s' % lit(root21(segst[35:53])), '',
             '/-- The INTAKE leaves (`WSB` phase 0). -/',
             'def leaves0 : List WsLeaf := [\n  ' + ',\n  '.join(l0) + ']', '',
             '/-- The chunk\'s committed changes (key, new value; `none` = removed), `state.json` `changes`. -/',
             'def writes : List (ArenaCore.Bytes × Option ArenaCore.Bytes) := [\n  ' + ',\n  '.join(
                 '(%s, %s)' % (blit(k), 'none' if v is None else 'some %s' % blit(v)) for k, v in st['changes']) + ']', '',
             '/-- The segment proof\'s public values 0..52 (`seg0/out/statement.json`): `wsLen`, `R_in`, `R_out` limbs. -/',
             'def pubSeg : List Nat := [%s]' % ', '.join(str(x) for x in segst[:53]), '',
             '/-- The leaves after the chunk\'s writes (`WSB` phase 1 = the last segment\'s output). -/',
             'def leaves1 : List WsLeaf := [\n  ' + ',\n  '.join(l1) + ']', '']
    open(out, 'w').write('\n'.join(lines) + '\nend %s\n' % ns)
    print(json.dumps(dict(keys=len(keys), D=D, written=sum(1 for k in keys if k in fin))))


if __name__ == '__main__':
    main()
