#!/usr/bin/env python3
"""Generate the FINAL AIR of another shape class from `lean/FinalM5d/Final.lean` (lane G, G-2 item 4).

The class-F1 AIR is parametric in exactly three constants: the shard count `NS`, and the
Reed-Solomon `(d, t) = (RSD, RST)` (the `FinIn` length follows: `FI_LEN = FI_SIDS + 8 NS`). This
script writes `lean/FinalM5d/Cls/C<NS>_<D>_<T>.lean`, a copy of `Final.lean` in namespace
`FinalM5d.C<NS>_<D>_<T>` with those constants replaced, and regenerates
`lean/FinalM5d/Cls/All.lean` (the class list `m5d-tool air-final-cls NS D T …` dispatches on).
`Cls/All.lean` also checks, by `rfl`, that the generated F1 copy is `finalAir` itself, so every F1
theorem is about the same AIR the generator produces.

  gen_class.py NS D T [NS D T ...]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "lean/FinalM5d/Final.lean")
OUT = os.path.join(HERE, "lean/FinalM5d/Cls")


def gen(ns, d, t):
    s = open(SRC).read()
    name = f"C{ns}_{d}_{t}"
    for k, v in (("NS", ns), ("RSD", d), ("RST", t)):
        s, n = re.subn(rf"^def {k} : Nat := \d+$", f"def {k} : Nat := {v}", s, flags=re.M)
        assert n == 1, k
    s, n = re.subn(r"^def FI_LEN : Nat := \d+$", "def FI_LEN : Nat := FI_SIDS + 8 * NS", s, flags=re.M)
    assert n == 1
    s = s.replace("namespace FinalM5d\n", f"namespace FinalM5d.{name}\n", 1)
    s = s.replace("end FinalM5d\n", f"end FinalM5d.{name}\n")
    # `S384`, `Rng` and the DSL are shared (class independent)
    s = s.replace("open ZkFormal.Air NearSpec NearSpecV3",
                  "open ZkFormal.Air NearSpec NearSpecV3 FinalM5d", 1)
    s = s.replace("/-!\n# FinalM5d.Final", f"/-! (generated by `gen_class.py {ns} {d} {t}` from `Final.lean`)\n# FinalM5d.Final", 1)
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, name + ".lean"), "w").write(s)
    return name


def main():
    a = [int(x) for x in sys.argv[1:]]
    assert len(a) % 3 == 0
    want = {(a[i], a[i + 1], a[i + 2]) for i in range(0, len(a), 3)} | {(6, 5, 16)}
    have = set()
    if os.path.isdir(OUT):
        for f in os.listdir(OUT):
            m = re.fullmatch(r"C(\d+)_(\d+)_(\d+)\.lean", f)
            if m:
                have.add(tuple(int(x) for x in m.groups()))
    names = [gen(*c) for c in sorted(want | have)]
    imp = "\n".join(f"import FinalM5d.Cls.{n}" for n in names)
    cases = "\n".join(
        f"  | {n.split('_')[0][1:]}, {n.split('_')[1]}, {n.split('_')[2]} => some "
        f"(FinalM5d.{n}.finalAir, FinalM5d.{n}.finalLayouts, FinalM5d.{n}.finalConsts)" for n in names)
    open(os.path.join(OUT, "All.lean"), "w").write(f"""{imp}
import FinalM5d.Final

/-! The generated FINAL classes (`gen_class.py`). The F1 copy is `finalAir` itself. -/

namespace FinalM5d.Cls

open ZkFormal.Air

/-- The FINAL AIR, its layouts and generator constants of class `(NS, d, t)`, if generated. -/
def byClass : Nat → Nat → Nat → Option (Air × List (String × Layout) × List (String × String))
{cases}
  | _, _, _ => none

theorem f1_eq : FinalM5d.C6_5_16.finalAir = FinalM5d.finalAir := rfl

end FinalM5d.Cls
""")
    print("classes:", ", ".join(names))


if __name__ == "__main__":
    main()
