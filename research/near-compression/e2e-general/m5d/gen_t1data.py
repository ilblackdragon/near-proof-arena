#!/usr/bin/env python3
"""Write lean/FinalM5d/T1Data.lean: T1's FIN-row byte values (from `m5d-tool dump`), for the Lean
non-vacuity instance `FinalM5d.T1Check`.   gen_t1data.py DUMP_JSON OUT_LEAN"""
import hashlib
import json
import sys

d = json.load(open(sys.argv[1]))
pre, post = bytes.fromhex(d['pre']), bytes.fromhex(d['post'])
stream = pre + bytes(4) + post   # lane E's canonical S
f = d['finIn']
acc0 = list(hashlib.sha384(b'').digest()[:42])


def chain(acc, items):
    for it in items:
        acc = list(hashlib.sha384(bytes(acc) + it).digest()[:42])
    return acc


leaves = [bytes.fromhex(x) for x in f['outcomeLeaves']]
items = [int(r['shard']).to_bytes(8, 'little') + len(bytes.fromhex(r['enc'])).to_bytes(4, 'little') +
         bytes.fromhex(r['enc']) for r in f['outgoing']]
fi = (bytes.fromhex(f['root']) + bytes.fromhex(f['congestion']) + int(f['gasUsed']).to_bytes(8, 'little') +
      int(f['balanceBurnt']).to_bytes(16, 'little') + int(f['gasLimit']).to_bytes(8, 'little') + b'\x00' +
      bytes(4) + bytes(4) + bytes(chain(acc0, leaves)) + bytes(chain(acc0, items)) + bytes(acc0) +
      (6).to_bytes(4, 'little') + b''.join(int(s).to_bytes(8, 'little') for s in f['shardIds']))
assert len(fi) == 294
o = d['outputs']


def L(b):
    return '[' + ', '.join(str(x) for x in b) + ']'


out = f'''import FinalM5d.HeaderLink

/-! Generated by `gen_t1data.py` from T1's `m5d-tool dump` (`d3c8/d3/02-h10196-s3`): the FIN row's
statement window, `FinIn`, the three computed roots (= the checker's outputs) and the body length. -/

namespace FinalM5d.T1

def hb : List Nat := {L(stream[:424])}
def fi : List Nat := {L(fi)}
def ro : List Nat := {L(bytes.fromhex(o['outcomeRoot']))}
def rs : List Nat := {L(bytes.fromhex(o['encodedMerkleRoot']))}
def rsh : List Nat := {L(bytes.fromhex(o['outgoingRoot']))}
def n : Nat := {int(o['encodedLength'])}
/-- The public `chunk_inner` of T1's claim. -/
def chunkInner : List Nat := {L(bytes.fromhex(d['chunkInner']))}
/-- The checker's outputs (`tailNew`): state root, gas used, gas limit, balance burnt. -/
def stateRoot : List Nat := {L(bytes.fromhex(o['stateRoot']))}
def gasUsed : Nat := {int(o['gasUsed'])}
def gasLimit : Nat := {int(o['gasLimit'])}
def balanceBurnt : Nat := {int(o['balanceBurnt'])}

end FinalM5d.T1
'''
open(sys.argv[2], 'w').write(out)
