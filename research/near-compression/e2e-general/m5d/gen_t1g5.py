#!/usr/bin/env python3
"""Write lean/FinalM5d/T1G5Data.lean (G-5): the public values of T1's INIT and FINAL leaves and lane I's
chain digests h(c0), h(c10), for the Lean non-vacuity instance `FinalM5d.T1G5`.

  gen_t1g5.py INIT_PUBS FINAL_PUBS CHAIN_JSON OUT_LEAN

INIT_PUBS / FINAL_PUBS: a `pubs.bin` (u32 LE per value) or a `statement.json` (`public_values`, per
AIR, or `statement`); CHAIN_JSON: `t1/chain.py plan`'s `chain.json` (`digests`)."""
import json
import struct
import sys


def pubs(p):
    if p.endswith('.bin'):
        b = open(p, 'rb').read()
        return list(struct.unpack('<%dI' % (len(b) // 4), b))
    j = json.load(open(p))
    return [int(x) for x in j['statement']]


def nat_list(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


def main():
    pi, pf, ch, out = sys.argv[1:5]
    ds = json.load(open(ch))['digests']
    I, F = pubs(pi), pubs(pf)
    assert len(I) == 44 and len(F) == 82, (len(I), len(F))
    L = ['/-! Generated by `gen_t1g5.py`: T1\'s INIT (44) / FINAL (82) public values (G-5 proofs) and lane I\'s',
         'chain digests `h(c0)`, `h(c10)` (`t1/chain.py plan`, `chain.json`). -/', '',
         'namespace FinalM5d.T1G5', '',
         f'def pubI : List Nat := {nat_list(I)}',
         f'def pubF : List Nat := {nat_list(F)}',
         f'def c0 : List Nat := {nat_list(bytes.fromhex(ds[0]))}',
         f'def c10 : List Nat := {nat_list(bytes.fromhex(ds[10]))}', '',
         'end FinalM5d.T1G5', '']
    open(out, 'w').write('\n'.join(L))


if __name__ == '__main__':
    main()
