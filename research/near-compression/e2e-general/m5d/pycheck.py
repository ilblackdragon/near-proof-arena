#!/usr/bin/env python3
"""Pure-Python precheck of a dumped M5d trace against the exported AIR (lane G, G-2).

Every exported constraint on every row of every Lean table, multiplicity bits boolean, and every
bus balanced as a multiset — except the chip bus (Lean bus 16, `IF384`, whose sender is the native
SHA-512 chip) and the SHA-256 table (its trace is generated by the prover from `sha_msgs.json`:
its two buses are checked here as "every receive / send of a consumer is one of the listed
messages"). Then the statement check (public values = the statement's). A reference for the prover's own
precheck, small memory (no proving); it does not see the chip's side of `IF384`.

  pycheck.py AIR_JSON NAMES_JSON DUMP_DIR
"""
import json, struct, sys, collections, hashlib

P = 2013265921
CHIP_BUS = 16


def load(path):
    b = open(path, 'rb').read()
    log, w = struct.unpack('<II', b[:8])
    h = 1 << log
    vals = struct.unpack('<%dI' % (h * w), b[8:8 + 4 * h * w])
    return [vals[r * w:(r + 1) * w] for r in range(h)]


def compile_expr(e):
    t = e[0]
    if t == 'c':
        v = e[1] % P
        return lambda cur, nxt, pubs, sel: v
    if t == 'v':
        i, nx = e[1], e[2]
        return (lambda cur, nxt, pubs, sel: nxt[i]) if nx else (lambda cur, nxt, pubs, sel: cur[i])
    if t == 'p':
        i = e[1]
        return lambda cur, nxt, pubs, sel: pubs[i] if i < len(pubs) else 0
    if t in ('first', 'last', 'trans'):
        k = ('first', 'last', 'trans').index(t)
        return lambda cur, nxt, pubs, sel: sel[k]
    if t in ('+', '*'):
        a, b = compile_expr(e[1]), compile_expr(e[2])
        if t == '+':
            return lambda cur, nxt, pubs, sel: (a(cur, nxt, pubs, sel) + b(cur, nxt, pubs, sel)) % P
        return lambda cur, nxt, pubs, sel: a(cur, nxt, pubs, sel) * b(cur, nxt, pubs, sel) % P
    a = compile_expr(e[1])
    return lambda cur, nxt, pubs, sel: (-a(cur, nxt, pubs, sel)) % P


def main():
    air, names, d = json.load(open(sys.argv[1])), json.load(open(sys.argv[2])), sys.argv[3]
    pb = open(d + '/pubs.bin', 'rb').read()
    pubs = list(struct.unpack('<%dI' % (len(pb) // 4), pb))
    bus = collections.defaultdict(collections.Counter)
    bad = 0
    sha_tables = []
    for ti, (tn, t) in enumerate(zip(names['tables'], air['tables'])):
        if tn == 'SHA':
            sha_tables.append(ti)
            continue
        rows = load('%s/%s.bin' % (d, tn))
        h = len(rows)
        cons = [compile_expr(c) for c in t['constraints']]
        ixs = [(i['bus'], i['send'], [compile_expr(m) for m in i['mult']], [compile_expr(m) for m in i['msg']])
               for i in t['interactions']]
        for r in range(h):
            cur, nxt = rows[r], rows[(r + 1) % h]
            sel = (int(r == 0), int(r == h - 1), int(r != h - 1))
            for ci, c in enumerate(cons):
                if c(cur, nxt, pubs, sel):
                    if bad < 5:
                        print('CONSTRAINT FAIL', tn, 'row', r, 'constraint', ci)
                    bad += 1
            for (b, s, mult, msg) in ixs:
                m = 0
                for k, mb in enumerate(mult):
                    x = mb(cur, nxt, pubs, sel)
                    if x not in (0, 1):
                        if bad < 5:
                            print('MULT NOT BIT', tn, 'row', r, 'bus', b)
                        bad += 1
                    m += x << k
                if m:
                    bus[(b, s)][tuple(f(cur, nxt, pubs, sel) for f in msg)] += m
    # the SHA-256 table: its messages are the generator's list
    if sha_tables:
        sha = json.load(open(d + '/sha_msgs.json'))
        for mm in sha:
            mid, by = mm['id'], bytes.fromhex(mm['bytes'])
            for i, x in enumerate(by):
                bus[(0, False)][(mid % P, i, x)] += 1
            dg = hashlib.sha256(by).digest()
            bus[(1, True)][(mid % P, len(by)) + tuple(dg)] += 1
    for b in sorted({k[0] for k in bus}):
        if b == CHIP_BUS:
            continue
        snd, rcv = bus[(b, True)], bus[(b, False)]
        if snd != rcv:
            diff = (snd - rcv) + (rcv - snd)
            print('BUS UNBALANCED', b, 'distinct differing messages', len(diff), 'e.g.', list(diff.items())[:2])
            bad += 1
    sb = open(d + '/stmt_pubs.bin', 'rb').read()
    if sb != pb:
        print('STATEMENT MISMATCH (public values differ from the statement)')
        bad += 1
    print('PYCHECK', 'OK' if bad == 0 else 'FAIL (%d)' % bad)
    sys.exit(0 if bad == 0 else 1)


if __name__ == '__main__':
    main()
