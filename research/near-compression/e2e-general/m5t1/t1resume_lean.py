#!/usr/bin/env python3
"""F-4: write `lean/M5T1/T1ResumeData.lean` from the resume leaf's measured data.

    t1resume_lean.py DATA_DIR OUT.lean

DATA_DIR holds the files `tracegen.py` writes for the resume leaf (`run.sh … leaves`):
`t1-resume-pubs.json` (the 1,531 public values), `t1-rb-row0.json` (`RB`'s row 0 by column name),
`t1-acc.json` (the two accumulator appends: `acc_in`, `item_ser` = the Lean run's `Ser.enc` of the
outcome / refund receipt, `acc_out`). The Lean file only carries the numbers; `T1Resume.lean`
checks them in the kernel."""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "t1"))
import bndrec  # noqa: E402


def nat_list(name, xs, per=24):
    lines = []
    for i in range(0, len(xs), per):
        lines.append("  " + ", ".join(str(x) for x in xs[i:i + per]))
    return f"def {name} : List Nat :=\n  [" + ",\n".join(lines).lstrip() + "]\n"


def main():
    d, out = sys.argv[1], sys.argv[2]
    pubs = json.load(open(f"{d}/t1-resume-pubs.json"))
    assert len(pubs) == 1531 and all(0 <= x < 256 for x in pubs)
    rb = json.load(open(f"{d}/t1-rb-row0.json"))
    names = ["tgo"] + [f"rso.{j}" for j in range(42)] + ["tgi"] + [f"rsi.{j}" for j in range(42)] + \
        [f"cri.{j}" for j in range(7)]
    row = [int(rb[n]) for n in names]
    acc = json.load(open(f"{d}/t1-acc.json"))["hashes"]
    assert [h["hid"] for h in acc] == [0, 1]
    s = ["import M5T1.Rb", "import NearSpecV3.E2E.Boundary", "", "/-! Generated by `m5t1/t1resume_lean.py` from the T1 resume leaf's data (F-4). -/", "",
         "namespace M5T1.T1ResumeData", ""]
    s.append(nat_list("pubN", pubs))
    s.append(nat_list("rbRowN", row))
    for h in acc:
        k = h["hid"]
        s.append(nat_list(f"accIn{k}N", list(bytes.fromhex(h["acc_in"]))))
        s.append(nat_list(f"item{k}N", list(bytes.fromhex(h["item_ser"]))))
        s.append(nat_list(f"accOut{k}N", list(bytes.fromhex(h["acc_out"]))))
    # the input record B_in round-trips through lane I's codec (`bndrec`, cross-checked there
    # against Lean's `BndRec.encode`); the kernel check of the record encoding exceeds the 5-GB
    # budget, so `T1Resume` checks the fields the rules read instead
    rin = bndrec.decode(bytes(pubs[247:247 + 834]))
    assert bndrec.encode(rin) == bytes(pubs[247:247 + 834])
    s.append("def bs (l : List Nat) : ArenaCore.Bytes := l.map UInt8.ofNat\n")
    s += ["end M5T1.T1ResumeData", ""]
    open(out, "w").write("\n".join(s))


if __name__ == "__main__":
    main()
