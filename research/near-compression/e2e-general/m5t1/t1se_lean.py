#!/usr/bin/env python3
"""F-5 / F-7: write `lean/M5T1/T1SeData.lean` from the three T1 STATE engine-half dumps (`segen.py`).

    t1se_lean.py OUT.lean SEG_A_DIR SEG_B_DIR FINALIZE_DIR

Each dir holds `t1-se.json` (the 900 public values = `BndRec.encode` of the chain's two cut records,
and `SE`'s row 0). The Lean file only carries the numbers; `T1Se.lean` checks them in the kernel."""
import json
import sys


def nat_list(name, xs, per=24):
    rows = [", ".join(str(x) for x in xs[i:i + per]) for i in range(0, len(xs), per)]
    return f"def {name} : List Nat :=\n  [" + ",\n   ".join(rows) + "]\n"


def main():
    out, dirs = sys.argv[1], sys.argv[2:]
    s = ["import M5T1.Se", "", "/-! Generated by `m5t1/t1se_lean.py` from T1's STATE engine-half leaves (F-5; F-7: on the M14 chain,",
         "with the opening rows): lane I's chain cuts c1 → c2 (seg A), c7 → c8 (seg B), c8 → c9 (finalize). -/", "", "namespace M5T1.T1SeData", ""]
    for tag, d in zip(["A", "B", "F"], dirs):
        j = json.load(open(f"{d}/t1-se.json"))
        assert len(j["pubs"]) == 900 and all(0 <= x < 256 for x in j["pubs"])
        s.append(f"-- {j['leaf']}: c{j['cuts'][0]} → c{j['cuts'][1]}, d_in {j['d_in'][:16]}…, d_out {j['d_out'][:16]}…")
        s.append(nat_list(f"pub{tag}", j["pubs"]))
        # F-7: the whole `SE` row 0 (the opening rows' columns too), in the layout's order
        s.append(nat_list(f"row{tag}", list(j["se_row0"].values())))
    s += ["end M5T1.T1SeData", ""]
    open(out, "w").write("\n".join(s))


if __name__ == "__main__":
    main()
