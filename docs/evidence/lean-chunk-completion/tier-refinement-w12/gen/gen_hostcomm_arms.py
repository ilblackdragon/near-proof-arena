"""Generate spec/lean/v3/NearSpecV3/Successor/HostCommArms.lean.

Usage (from the repository root):
  python3 docs/evidence/lean-chunk-completion/tier-refinement-w12/gen/gen_hostcomm_arms.py \
    spec/lean/v3/NearSpecV3/Successor/HostCommArms.lean

The arm list (equation index and name of every `hostCall` / `cryptoHostCall` arm) is read from
`Wasm/FuelHost.lean`, whose `HOR_hc_N` / `HOR_cc_N` theorems enumerate the same equation lemmas.
"""
import re, sys
fh=open('spec/lean/v3/NearSpecV3/Wasm/FuelHost.lean').read()
arms=re.findall(r'theorem HOR_hc_(\d+) \(r : St\) \(h : HM Unit\) \(hh : hostCall "([a-z0-9_]+)"', fh)
crypto=re.findall(r'theorem HOR_cc_\d+ \(r : St\) \(h : HM Unit\) \(hh : cryptoHostCall "([a-z0-9_]+)"', fh)
assert len(arms)==75 and len(crypto)==14, (len(arms), len(crypto))
ga={"promise_batch_action_state_init","promise_batch_action_state_init_by_account_id",
 "set_state_init_data_entry","promise_batch_action_deploy_global_contract",
 "promise_batch_action_deploy_global_contract_by_account_id",
 "promise_batch_action_use_global_contract","promise_batch_action_use_global_contract_by_account_id",
 "promise_batch_action_add_gas_key_with_full_access",
 "promise_batch_action_add_gas_key_with_function_call","promise_batch_action_transfer_to_gas_key"}
assert all(g in [x[1] for x in arms] for g in ga)
o=[]
o.append('''import NearSpecV3.Successor.HostComm
import NearSpecV3.Wasm.CryptoHost

/-!
# W12 — every host arm commutes with the interpreter-flag map (generated)

One theorem per `hostCall` / `cryptoHostCall` arm, over its equation lemma, closed by `cr`
(`HostComm.lean`). The ten arms named in `globalPromiseHosts` read `St.globalActions` (`Host.lean`
571, 577, 592, 615, 1167, 1179, 1199 are in them); they commute with every map that leaves that flag
alone (`setF oc none`). Every other arm commutes with every `setF oc og`.

Summary theorems: `CR_hostCall` (non-global names, any map), `CR_hostCall_none` (every name,
`og = none`), `CR_cryptoHostCall` (any map), `CR_dispatchArm`, `CR_dispatchArm_none`.
Generated by `docs/evidence/lean-chunk-completion/tier-refinement-w12/gen/gen_hostcomm_arms.py`.
-/

namespace NearSpecV3.Successor.HostComm

open NearSpecV3.Wasm

set_option maxRecDepth 100000
''')
for n,name in arms:
    if name in ga:
        o.append(f'''set_option maxHeartbeats 0 in
theorem CR_hc_{n} (oc : Option Bool) (h : HM Unit) (hh : hostCall "{name}" = some h) :
    CR (setF oc none) h h := by
  rw [hostCall.eq_{n}] at hh; have hh2 := Option.some.inj hh; clear hh; subst hh2; cr
''')
    else:
        o.append(f'''set_option maxHeartbeats 0 in
theorem CR_hc_{n} (oc og : Option Bool) (h : HM Unit) (hh : hostCall "{name}" = some h) :
    CR (setF oc og) h h := by
  rw [hostCall.eq_{n}] at hh; have hh2 := Option.some.inj hh; clear hh; subst hh2; cr
''')
o.append('''section
variable (oc og : Option Bool)
theorem CR_blsWriter (base element : Cost) (itemSize : Nat) (fnName : String)
    (decode : ArenaCore.Bytes → Option ArenaCore.Bytes) (a : Vector Nat 3) :
    CR (setF oc og) (blsWriter base element itemSize fnName decode a)
      (blsWriter base element itemSize fnName decode a) := by
  unfold blsWriter; cr
theorem CR_altBn128Writer (base element : Cost) (itemSize : Nat)
    (decode : ArenaCore.Bytes → Option ArenaCore.Bytes) (a : Vector Nat 3) :
    CR (setF oc og) (altBn128Writer base element itemSize decode a) (altBn128Writer base element itemSize decode a) := by
  unfold altBn128Writer; cr
theorem CR_hostEcrecover (a : Vector Nat 7) : CR (setF oc og) (hostEcrecover a) (hostEcrecover a) := by
  unfold hostEcrecover; cr
theorem CR_hostP256Verify (a : Vector Nat 6) : CR (setF oc og) (hostP256Verify a) (hostP256Verify a) := by
  unfold hostP256Verify; cr
theorem CR_hostPairingCheck (a : Vector Nat 2) : CR (setF oc og) (hostPairingCheck a) (hostPairingCheck a) := by
  unfold hostPairingCheck; cr
theorem CR_hostAltBn128PairingCheck (a : Vector Nat 2) :
    CR (setF oc og) (hostAltBn128PairingCheck a) (hostAltBn128PairingCheck a) := by
  unfold hostAltBn128PairingCheck; cr
end
''')
o.append('''/-- Every curve-host arm commutes with every flag map. -/
theorem CR_cryptoHostCall (oc og : Option Bool) (name : String) (h : HM Unit)
    (hh : cryptoHostCall name = some h) : CR (setF oc og) h h := by''')
wr={'ecrecover':'CR_hostEcrecover oc og _','p256_verify':'CR_hostP256Verify oc og _',
 'alt_bn128_pairing_check':'CR_hostAltBn128PairingCheck oc og _','bls12381_pairing_check':'CR_hostPairingCheck oc og _'}
for i,name in enumerate(crypto,1):
    w=wr.get(name, 'CR_altBn128Writer oc og _ _ _ _ _' if name.startswith('alt_bn128') else 'CR_blsWriter oc og _ _ _ _ _ _')
    o.append(f'''  by_cases h{i} : name = "{name}"
  · subst h{i}; rw [cryptoHostCall.eq_{i}] at hh; have hh2 := Option.some.inj hh; clear hh; subst hh2
    exact CR_bind (CR_popArgs oc og _) (fun _ => {w})''')
hs=' '.join(f'h{i}' for i in range(1,len(crypto)+1))
o.append(f'''  rw [cryptoHostCall.eq_{len(crypto)+1} name {hs}] at hh; cases hh
''')
def chain(thname, sig, concl, body_ga, body_other):
    out=[f'''theorem {thname} {sig} :
    {concl} := by''']
    for n,name in arms:
        out.append(f'''  by_cases h{n} : name = "{name}"
  · subst h{n}; {body_ga(n) if name in ga else body_other(n)}''')
    hs=' '.join(f'h{n}' for n,_ in arms)
    out.append(f'''  rw [hostCall.eq_{len(arms)+1} name {hs}] at hh; cases hh
''')
    return '\n'.join(out)
o.append('/-- Every non-global host arm commutes with every flag map. -/')
o.append(chain('CR_hostCall','(oc og : Option Bool) (name : String) (h : HM Unit) (hh : hostCall name = some h)\n    (hn : globalPromiseHosts.contains name = false)','CR (setF oc og) h h',
  lambda n: 'exact absurd hn (by decide)', lambda n: f'exact CR_hc_{n} oc og h hh'))
o.append('/-- Every host arm commutes with every map that leaves `globalActions` alone. -/')
o.append(chain('CR_hostCall_none','(oc : Option Bool) (name : String) (h : HM Unit) (hh : hostCall name = some h)','CR (setF oc none) h h',
  lambda n: f'exact CR_hc_{n} oc h hh', lambda n: f'exact CR_hc_{n} oc none h hh'))
o.append('''/-- A non-global dispatch arm commutes with every flag map. -/
theorem CR_dispatchArm (oc og : Option Bool) (s : St) (name : String) (h : HM Unit)
    (hh : dispatchArm s name = some h) (hn : globalPromiseHosts.contains name = false) :
    CR (setF oc og) h h := by
  unfold dispatchArm at hh
  cases hc : hostCall name with
  | some h' =>
    rw [hc] at hh; simp only [Option.some.injEq] at hh; subst hh; exact CR_hostCall oc og name _ hc hn
  | none =>
    rw [hc] at hh
    simp only at hh
    split at hh
    · exact CR_cryptoHostCall oc og name h hh
    · cases hh

/-- Every dispatch arm commutes with every map that leaves `globalActions` alone. -/
theorem CR_dispatchArm_none (oc : Option Bool) (s : St) (name : String) (h : HM Unit)
    (hh : dispatchArm s name = some h) : CR (setF oc none) h h := by
  unfold dispatchArm at hh
  cases hc : hostCall name with
  | some h' =>
    rw [hc] at hh; simp only [Option.some.injEq] at hh; subst hh; exact CR_hostCall_none oc name _ hc
  | none =>
    rw [hc] at hh
    simp only at hh
    split at hh
    · exact CR_cryptoHostCall oc none name h hh
    · cases hh

#print axioms CR_hostCall
#print axioms CR_hostCall_none
#print axioms CR_cryptoHostCall
#print axioms CR_dispatchArm
#print axioms CR_dispatchArm_none

end NearSpecV3.Successor.HostComm
''')
open(sys.argv[1],'w').write('\n'.join(o))
