"""Generate spec/lean/v3/NearSpecV3/Successor/HostQ.lean.

Usage (from the repository root):
  python3 docs/evidence/lean-chunk-completion/tier-refinement-w12/gen/gen_hostq.py \
    spec/lean/v3/NearSpecV3/Successor/HostQ.lean

The commutation proofs of `HostComm.lean` / `HostCommStep.lean` for the flag map `setF oc og`, with
the map `setX x` (action log, trie-backed store and global-actions flag taken from `x`) in its place.
"""
import re, sys
hc = open('spec/lean/v3/NearSpecV3/Successor/HostComm.lean').read().split('\n')
hs = open('spec/lean/v3/NearSpecV3/Successor/HostCommStep.lean').read().split('\n')


def tr(s):
    s = s.replace('setF oc og', 'setX q0').replace('{oc og : Option Bool}', '{q0 : St}')
    s = s.replace('(oc og : Option Bool)', '(q0 : St)').replace('(oc := oc) (og := og)', '(q0 := q0)')
    s = re.sub(r'\bF_', 'X_', s)
    s = s.replace('forIn_F', 'forIn_X').replace("forIn'_F", "forIn'_X")
    s = re.sub(r'\bsf_step\b', 'sx_step', s)
    s = re.sub(r'\bsf\b', 'sx', s)
    return s


start = [i for i, l in enumerate(hc) if l.startswith('@[simp] theorem F_stack')][0]
end_ = [i for i, l in enumerate(hc) if l.startswith('theorem F_writeBytes')][0] + 5
skip = ['F_actions', 'F_real ', 'F_trieGet', 'F_dataIdOf', 'F_receiptReceiver', 'F_globalActions_none',
        'F_curveHosts_none', 'The global-actions flag under']
proj = [tr(l) for l in hc[start:end_] if not any(k in l for k in skip)]
proj = '\n'.join(proj).replace('\nend\n', '\n')
proj = proj.replace('@[simp] theorem X_memBytes', '@[simp] theorem X_curveHosts : (setX q0 t).curveHosts = t.curveHosts := rfl\n@[simp] theorem X_memBytes')
step_start = [i for i, l in enumerate(hs) if l.startswith('syntax "sf_step"')][0]
step_end = [i for i, l in enumerate(hs) if l.startswith('theorem F_topCount')][0] + 1
body = '\n'.join(tr(l) for l in hs[step_start:step_end])
body = body.replace(', X_actions', '').replace(', X_real', '').replace('X_subsidized,', 'X_subsidized, X_curveHosts,')
out = '''import NearSpecV3.Successor.HostCommStep

/-!
# W12 / O3 — the non-call instructions keep the action log, the store and the global-actions flag

`setX x s` overwrites `s`'s action log, trie-backed store and global-actions flag by `x`'s. Every
machine helper and every instruction but the two calls commutes with it (`X_exec`; the proofs are the
`setF` ones of `HostCommStep.lean`, generated by `gen/gen_hostq.py`). Read at `x := s` this says those
instructions keep the three fields.
-/
namespace NearSpecV3.Successor.HostComm
open NearSpecV3.Wasm

def setX (x : St) (s : St) : St :=
  { s with actions := x.actions, real := x.real, globalActions := x.globalActions }

theorem setX_self (s : St) : setX s s = s := rfl

section
variable (q0 : St) (t : St)
''' + proj + '''
end

/-- Fold a structure literal over `setX x s`'s three fields back into `setX`. -/
theorem X_mk (q0 : St) (s : St) (a1 a2 a3 a4 a5 a6 a7 a8 a9 a10 a11 a12 a13 a14 a15 a16 a17 a18 a19 a20 a22 a24 a26) :
    St.mk a1 a2 a3 a4 a5 a6 a7 a8 a9 a10 a11 a12 a13 a14 a15 a16 a17 a18 a19 a20 (setX q0 s).actions a22
        (setX q0 s).real a24 (setX q0 s).globalActions a26 =
      setX q0 (St.mk a1 a2 a3 a4 a5 a6 a7 a8 a9 a10 a11 a12 a13 a14 a15 a16 a17 a18 a19 a20 s.actions a22
        s.real a24 s.globalActions a26) := rfl

''' + body + '''
end

set_option maxHeartbeats 10000000 in
/-- Every instruction but the two calls commutes with `setX q0`. -/
theorem X_exec (cfg : NearCfg) (p : Prepared) (s : St) (f : Frame) (pf : PFunc) (i : Instr)
    (h1 : ∀ fi, i ≠ .call fi) (h2 : ∀ ty y, i ≠ .callIndirect ty y) (q0 : St) :
    exec cfg p (setX q0 s) f pf i = mapRes (setX q0) (exec cfg p s f pf i) := by
  cases i with
  | call fi => exact absurd rfl (h1 fi)
  | callIndirect ty y => exact absurd rfl (h2 ty y)
  | _ => simp only [exec]; sx

end NearSpecV3.Successor.HostComm
'''
open(sys.argv[1], 'w').write(out)
