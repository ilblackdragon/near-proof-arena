"""Generate spec/lean/v3/NearSpecV3/Successor/HostQArms.lean.

Usage (from the repository root):
  python3 docs/evidence/lean-chunk-completion/tier-refinement-w12/gen/gen_hostq_arms.py \
    spec/lean/v3/NearSpecV3/Successor/HostQArms.lean

The helper list and the arm list (equation index and name of every `hostCall` / `cryptoHostCall`
arm) are read from `Wasm/FuelHost.lean` (`HOR_*`, `HOR_hc_N`, `HOR_cc_N`): the same walk, with the
lower-run invariant `LowQ` (global-actions flag off, trie-backed, no raw action) in place of
`HostMono`. The ten `globalPromiseHosts` arms are not generated: the lower run never reaches them
(`callHost` excludes every `realOodHosts` name on a trie-backed state with the flag off).
"""
import re, sys
fh = open('spec/lean/v3/NearSpecV3/Wasm/FuelHost.lean').read()
lines = fh.split('\n')
arms = re.findall(r'theorem HOR_hc_(\d+) \(r : St\) \(h : HM Unit\) \(hh : hostCall "([a-z0-9_]+)"', fh)
crypto = re.findall(r'theorem HOR_cc_(\d+) \(r : St\) \(h : HM Unit\) \(hh : cryptoHostCall "([a-z0-9_]+)"', fh)
assert len(arms) == 75 and len(crypto) == 14, (len(arms), len(crypto))
ga = {"promise_batch_action_state_init", "promise_batch_action_state_init_by_account_id",
      "set_state_init_data_entry", "promise_batch_action_deploy_global_contract",
      "promise_batch_action_deploy_global_contract_by_account_id",
      "promise_batch_action_use_global_contract", "promise_batch_action_use_global_contract_by_account_id",
      "promise_batch_action_add_gas_key_with_full_access",
      "promise_batch_action_add_gas_key_with_function_call", "promise_batch_action_transfer_to_gas_key"}
assert all(g in [x[1] for x in arms] for g in ga)
# helpers used only by the global arms (not needed, and they write raw actions)
skip_helpers = {'deployGlobalH', 'useGlobalH', 'stateInitH', 'setStateInitDataH', 'payGasKeyAddH', 'pushAction'}
h0 = [i for i, l in enumerate(lines) if l.startswith('theorem HOR_hErr')][0]
h1 = [i for i, l in enumerate(lines) if l.startswith('/-! ## Per-arm (generated)')][0]
helpers = []
i = h0
while i < h1:
    l = lines[i]
    m = re.match(r'theorem HOR_(\w+)', l)
    if m and m.group(1) in skip_helpers:
        i += 2
        continue
    if l.startswith('end'):
        i += 1
        continue
    l = l.replace('HOR r (', 'HQ (').replace('HOR r ((', 'HQ ((').replace('HOR_', 'HQ_')
    l = re.sub(r'\bhr\b', 'hq', l).replace('hr_call', 'hq_call')
    helpers.append(l)
    i += 1

o = []
o.append(r'''import NearSpecV3.Successor.HostQ

/-!
# W12 / O3 — the lower run's invariant survives every host arm it can reach (generated)

`LowQ s`: the global-actions flag is off, the store is trie-backed (`real = some _`) and the action
log holds no raw (global) action. `HQ x`: from every state satisfying `LowQ`, running `x` ends, with a
value or an error, in a state satisfying `LowQ` (errors included: the recorded call reads the log of
an aborted call too). The walk is `FuelHost.lean`'s `HOR` walk with `LowQ` in place of `HostMono`.

One theorem per `hostCall` arm outside `globalPromiseHosts` (65) and per `cryptoHostCall` arm (14).
Summaries: `HQ_hostCall`, `HQ_cryptoHostCall`, `HQ_dispatchArm`.
Generated by `docs/evidence/lean-chunk-completion/tier-refinement-w12/gen/gen_hostq_arms.py`.
-/

namespace NearSpecV3.Successor.HostComm
open NearSpecV3.Wasm

set_option maxRecDepth 100000

/-- The lower (flag-off) run's invariant. -/
structure LowQ (s : St) : Prop where
  ga : s.globalActions = false
  real : s.real.isSome = true
  noraw : ∀ e ∈ s.actions, e.rawAction = none

theorem LowQ.of {t u : St} (h : LowQ t) (h1 : u.globalActions = t.globalActions)
    (h2 : u.real.isSome = true ∨ u.real = t.real) (h3 : u.actions = t.actions) : LowQ u := by
  refine ⟨h1.trans h.ga, ?_, ?_⟩
  · rcases h2 with h2 | h2
    · exact h2
    · rw [h2]; exact h.real
  · rw [h3]; exact h.noraw

theorem isSome_map_of {α β : Type} (f : α → β) {o : Option α} (h : o.isSome = true) :
    (o.map f).isSome = true := by
  cases o
  · cases h
  · rfl

/-- `setX t v` carries `t`'s three fields. -/
theorem LowQ.ofSetX {t : St} (h : LowQ t) (v : St) : LowQ (setX t v) := ⟨h.ga, h.real, h.noraw⟩

theorem LowQ.ofPopN {t : St} (h : LowQ t) : LowQ (popN t).2 := by
  have e : (popN (setX t t)).2 = setX t (popN t).2 := congrArg Prod.snd (X_popN t t)
  rw [setX_self] at e
  rw [e]; exact h.ofSetX _

theorem LowQ.ofWriteBytes {t : St} (h : LowQ t) (a : Nat) (d : ByteArray) : LowQ (writeBytes t a d) := by
  have e := X_writeBytes t t a d
  rw [setX_self] at e
  rw [e]; exact h.ofSetX _

def resSt {α : Type} : EStateM.Result String St α → St
  | .ok _ s => s
  | .error _ s => s

/-- From every state satisfying `LowQ`, a run of `x` ends (value or error) satisfying `LowQ`. -/
def HQ {α : Type} (x : HM α) : Prop := ∀ s, LowQ s → LowQ (resSt (x.run s))

section

theorem HQ_pure {α : Type} (a : α) : HQ (pure a : HM α) := fun _ h => h

theorem HQ_throw {α : Type} (e : String) : HQ (throw e : HM α) := fun _ h => h

theorem HQ_bind {α β : Type} {x : HM α} {f : α → HM β} (h1 : HQ x) (h2 : ∀ a, HQ (f a)) :
    HQ (x >>= f) := by
  intro s hs
  have h := h1 s hs
  simp only [EStateM.run] at h ⊢
  change LowQ (resSt (EStateM.bind x f s))
  unfold EStateM.bind
  revert h
  cases x s with
  | ok a t => intro h; exact h2 a t h
  | error e t => intro h; exact h

theorem HQ_get_bind {β : Type} {f : St → HM β} (h : ∀ t, LowQ t → HQ (f t)) :
    HQ (get >>= f) := fun s hs => h s hs s hs

theorem HQ_set (u : St) (h : LowQ u) : HQ (set u : HM PUnit) := fun _ _ => h

theorem HQ_modify (f : St → St) (h : ∀ t, LowQ t → LowQ (f t)) : HQ (modify f : HM PUnit) :=
  fun s hs => h s hs

theorem HQ_ite {α : Type} (c : Prop) [Decidable c] {x y : HM α} (h1 : HQ x) (h2 : HQ y) :
    HQ (if c then x else y) := by
  by_cases hc : c <;> simp only [hc, ite_true, ite_false] <;> assumption

theorem HQ_dite {α : Type} (c : Prop) [Decidable c] {x : c → HM α} {y : ¬c → HM α}
    (h1 : ∀ h, HQ (x h)) (h2 : ∀ h, HQ (y h)) :
    HQ (if h : c then x h else y h) := by
  by_cases hc : c <;> simp only [hc, dite_true, dite_false] <;> apply_assumption

theorem HQ_forIn_list {β : Type} (l : List Nat) (b : β) (f : Nat → β → HM (ForInStep β))
    (h : ∀ i b, HQ (f i b)) : HQ (forIn l b f) := by
  induction l generalizing b with
  | nil => exact HQ_pure b
  | cons a l ih =>
    simp only [List.forIn_cons]
    apply HQ_bind (h a b); intro x
    cases x with
    | done b => exact HQ_pure b
    | yield b => exact ih b

theorem HQ_forIn {β : Type} (rg : Std.Legacy.Range) (b : β) (f : Nat → β → HM (ForInStep β))
    (h : ∀ i b, HQ (f i b)) : HQ (forIn rg b f) := by
  simp only [Std.Legacy.Range.forIn_eq_forIn_range']; exact HQ_forIn_list _ b f h

end

open Lean Elab Tactic Meta in
/-- Close `LowQ u` from some hypothesis `LowQ t` whose three fields `u` keeps (or whose store `u`
sets to `some _`). -/
elab "hq_of" : tactic => withMainContext do
  for d in (← getLCtx) do
    if d.isImplementationDetail then continue
    let ty ← instantiateMVars d.type
    if ty.isAppOf ``LowQ then
      let h ← Term.exprToSyntax d.toExpr
      let tacs : List (TSyntax `tactic) := [
        ← `(tactic| exact LowQ.of $h rfl (Or.inr rfl) rfl),
        ← `(tactic| exact LowQ.of $h rfl (Or.inl rfl) rfl),
        ← `(tactic| exact LowQ.of $h rfl (Or.inl (isSome_map_of _ (LowQ.real $h))) rfl)]
      for t in tacs do
        let s ← saveState
        try
          evalTactic t
          if (← getUnsolvedGoals).isEmpty then return
          s.restore
        catch _ => s.restore
  throwError "hq_of: no invariant hypothesis fits"

/-- Close `LowQ u` from the hypotheses. -/
macro "hq_close" : tactic => `(tactic| first
  | assumption
  | exact LowQ.ofWriteBytes ‹_› _ _
  | exact LowQ.ofPopN ‹_›
  | hq_of
  | (split <;> first | assumption | hq_of)
  | (rename_i hh; rw [Prod.ext_iff] at hh; obtain ⟨_, hh2⟩ := hh; rw [← hh2]; exact LowQ.ofPopN ‹_›))

syntax "hq_call" : tactic
macro_rules | `(tactic| hq_call) => `(tactic| first | exact HQ_pure _ | exact HQ_throw _)

open Lean Elab Tactic Meta in
/-- `intro`, only on propositions. -/
elab "hq_intro" : tactic => do
  let g ← getMainGoal
  let t ← instantiateMVars (← g.getType)
  unless t.consumeMData.isForall do throwError "hq_intro: not a binder"
  unless (← isProp t) do throwError "hq_intro: not a proposition"
  evalTactic (← `(tactic| intro))

syntax "hq_step" : tactic
macro_rules | `(tactic| hq_step) => `(tactic| first
  | contradiction
  | ((with_reducible apply HQ_get_bind); intro _ _)
  | (with_reducible apply HQ_pure)
  | (with_reducible apply HQ_throw)
  | ((with_reducible apply HQ_set); hq_close)
  | ((with_reducible apply HQ_modify); intro _ _; hq_close)
  | (with_reducible apply HQ_ite)
  | (with_reducible apply HQ_dite)
  | (with_reducible hq_call)
  | (with_reducible apply HQ_forIn)
  | (with_reducible apply HQ_bind)
  | split
  | hq_intro
  | (simp only []))

macro "hq" : tactic => `(tactic| repeat (any_goals hq_step))

theorem HQ_withGas (f : Gas → Gas × Option String) : HQ (withGas f) := by unfold withGas; hq
macro_rules | `(tactic| hq_call) => `(tactic| apply HQ_withGas)

theorem HQ_realOpH (rs : TTN.RealStore) (f : TTN.RealStore → ByteArray → Gas → TTN.Out) (k : ByteArray) :
    HQ (realOpH rs f k) := by unfold realOpH; hq
macro_rules | `(tactic| hq_call) => `(tactic| apply HQ_realOpH)

theorem HQ_pushAction (a : MAct) (ha : a.rawAction = none) : HQ (pushAction a) := by
  unfold pushAction
  apply HQ_get_bind; intro t ht
  apply HQ_bind (HQ_set _ ?_) (fun _ => HQ_pure _)
  refine ⟨ht.ga, ht.real, ?_⟩
  intro e he
  rcases Array.mem_push.mp he with he | he
  · exact ht.noraw e he
  · rw [he]; exact ha
macro_rules | `(tactic| hq_call) => `(tactic| (apply HQ_pushAction; rfl))

section
''')
o.append('\n'.join(helpers))
o.append('''end

/-! ## Per-arm (generated) -/
''')
for n, name in arms:
    if name in ga:
        continue
    o.append(f'''set_option maxHeartbeats 0 in
theorem HQ_hc_{n} (h : HM Unit) (hh : hostCall "{name}" = some h) : HQ h := by
  rw [hostCall.eq_{n}] at hh; have hh2 := Option.some.inj hh; clear hh; subst hh2; hq
''')
for n, name in crypto:
    o.append(f'''set_option maxHeartbeats 0 in
theorem HQ_cc_{n} (h : HM Unit) (hh : cryptoHostCall "{name}" = some h) : HQ h := by
  rw [cryptoHostCall.eq_{n}] at hh; have hh2 := Option.some.inj hh; clear hh; subst hh2; hq
''')
out = ['''/-- Every host arm outside `globalPromiseHosts` keeps the lower run's invariant. -/
theorem HQ_hostCall (name : String) (h : HM Unit) (hh : hostCall name = some h)
    (hn : globalPromiseHosts.contains name = false) : HQ h := by''']
for n, name in arms:
    body = 'exact absurd hn (by decide)' if name in ga else f'exact HQ_hc_{n} h hh'
    out.append(f'''  by_cases h{n} : name = "{name}"
  · subst h{n}; {body}''')
hs = ' '.join(f'h{n}' for n, _ in arms)
out.append(f'''  rw [hostCall.eq_{len(arms)+1} name {hs}] at hh; cases hh
''')
o.append('\n'.join(out))
out = ['''/-- Every curve-host arm keeps the lower run's invariant. -/
theorem HQ_cryptoHostCall (name : String) (h : HM Unit) (hh : cryptoHostCall name = some h) : HQ h := by''']
for n, name in crypto:
    out.append(f'''  by_cases h{n} : name = "{name}"
  · subst h{n}; exact HQ_cc_{n} h hh''')
hs = ' '.join(f'h{n}' for n, _ in crypto)
out.append(f'''  rw [cryptoHostCall.eq_{len(crypto)+1} name {hs}] at hh; cases hh
''')
o.append('\n'.join(out))
o.append('''/-- Every dispatch arm outside `globalPromiseHosts` keeps the lower run's invariant. -/
theorem HQ_dispatchArm (s : St) (name : String) (h : HM Unit) (hh : dispatchArm s name = some h)
    (hn : globalPromiseHosts.contains name = false) : HQ h := by
  unfold dispatchArm at hh
  cases hc : hostCall name with
  | some h' =>
    rw [hc] at hh; simp only [Option.some.injEq] at hh; subst hh; exact HQ_hostCall name _ hc hn
  | none =>
    rw [hc] at hh
    simp only at hh
    split at hh
    · exact HQ_cryptoHostCall name h hh
    · cases hh

#print axioms HQ_hostCall
#print axioms HQ_cryptoHostCall
#print axioms HQ_dispatchArm

end NearSpecV3.Successor.HostComm
''')
open(sys.argv[1], 'w').write('\n'.join(o))
