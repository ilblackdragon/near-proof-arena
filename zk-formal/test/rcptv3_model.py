# ---------------------------------------------------------------- checks
def check(rows, pub, H, exp):
    bad = []
    for k in range(H):
        for ci, e in enumerate(CONS):
            if ev(e, rows, k, pub, H) != 0:
                bad.append(('C', k, ci)); break
    if bad: return bad[:5]
    sends, recvs = defaultdict(Counter), defaultdict(Counter)
    for k in range(H):
        for bus, snd, mu, msg in INTS:
            m = ev(mu, rows, k, pub, H)
            if m not in (0, 1): return [('mult', k, bus)]
            if m:
                t = tuple(ev(x, rows, k, pub, H) for x in msg)
                (sends if snd else recvs)[bus][t] += 1
    # BYTES
    got = defaultdict(dict)
    for (i, p, b), c in sends[0].items():
        if c != 1 or p in got[i]: return [('dupbyte', i, p)]
        got[i][p] = b
    eb = exp['bytes']
    if set(got) != set(eb): return [('ids', sorted(set(got) ^ set(eb))[:5])]
    for i in eb:
        if got[i] != eb[i]: return [('bytes', i)]
    # DIGEST receives
    for (i, ln, *d), c in recvs[1].items():
        msg = [got[i][p] for p in range(ln)]
        if sha(msg) != d: return [('digest', i)]
    # body
    body = exp['body']
    if sorted(got.get(K_RF, {}).items()) != [(8 + t, x) for t, x in enumerate(body)]: return [('body',)]
    # KEYNIB
    gk = defaultdict(list)
    for (w, t, s, la), c in sends[5].items():
        gk[w] += [(t, s, la)] * c
    if {w: sorted(v) for w, v in gk.items()} != {w: sorted(v) for w, v in exp['key'].items()}: return [('keynib',)]
    if recvs[6] != exp['final']: return [('final', recvs[6], exp['final'])]
    if sends[26] != exp['rcl']: return [('rcl', sends[26], exp['rcl'])]
    if sends[16] != recvs[16]: return [('srec',)]
    # AKC with akeyV3
    akS, akR = Counter(sends[27]), Counter(recvs[27])
    for vid, U in exp['ak_use'].items(): akS[(vid, 0)] += 1; akR[(vid, U)] += 1
    if akS != akR: return [('akc',)]
    # BND with bndV3
    bS, bR = Counter(sends[15]), Counter(recvs[15])
    for x, U in exp['bnd_use'].items():
        pos = x - STRIDE * exp['q']
        rec = (x, exp['lob'][pos], exp['hib'][pos], exp['hn'])
        bS[rec + (0,)] += 1; bR[rec + (U,)] += 1
    if bS != bR: return [('bnd',)]
    # MEM with acctV3
    mS, mR = Counter(sends[7]), Counter(recvs[7])
    for a, v in exp['accts'].items():
        vid = v['vid']
        if vid not in exp['last_write']: continue
        fin = exp['state'][a]
        for i in range(16):
            lk = u128(v['locked'])[i]; st = u64(v['stor'])[i] if i < 8 else 0
            mS[(vid, 0, i, u128(v['amt'])[i], lk, st)] += 1
            mR[(vid, exp['last_write'][vid], i, u128(fin['amt'])[i], lk, st)] += 1
    if mS != mR: return [('mem',)]
    return []

def main():
    seed = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    n = int(sys.argv[3]) if len(sys.argv) > 3 else 50
    rng = random.Random(seed)
    done = fails = 0
    stats = Counter()
    while done < n:
        inst = gen(rng)
        if inst is None: continue
        rows, pub, H, exp = build(inst, rng)
        res = check(rows, pub, H, exp)
        done += 1
        rcs = [rc for rs in inst['lists'] for rc in rs]
        stats['receipts'] += len(rcs); stats['sys'] += sum(rc['sys'] for rc in rcs)
        stats['ee'] += sum(rc['sys'] and rc['signer'] == rc['recv'] for rc in rcs)
        stats['empty_lists'] += sum(1 for rs in inst['lists'] if not rs)
        if res:
            fails += 1
            print('FAIL', done, res[:3])
            if res[0][0] == 'C':
                k, ci = res[0][1], res[0][2]
                print('  row', k, 'state', [st for st in range(4, 27) if rows[k][st] == 1], 'constraint', CONS[ci])
            if fails > 3: break
    print(f'{done} instances, {fails} failures; {dict(stats)}')

main()
