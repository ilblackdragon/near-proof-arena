def parse(s):
    toks = s.replace('(', ' ( ').replace(')', ' ) ').split()
    def go(i):
        assert toks[i] == '('
        op = toks[i + 1]; i += 2; args = []
        while toks[i] != ')':
            if toks[i] == '(':
                a, i = go(i); args.append(a)
            else:
                args.append(int(toks[i])); i += 1
        return (op, args), i + 1
    out = []; i = 0
    while i < len(toks):
        e, i = go(i); out.append(e)
    return out
