#!/usr/bin/env python3
"""Model check of the rcptV3 table (zk-formal/ZkFormal/NearV3/Rcpt/Tables/Rcpt*.lean).

Usage: lake env lean --run test/RcptExport.lean > rcpt_air.txt
       python3 test/rcptv3_model.py rcpt_air.txt [seed] [instances]

For random D0-shaped batches (applied source lists, named receivers inside the own routing
interval, system receipts incl. gas refunds with signer = receiver and present / absent
access keys, refunds, empty lists, repeated accounts) the honest trace is generated by the
design rules (v1's closed-form generator `Near/Render/Rcpt.lean` plus the v3 deltas), then:
  * every exported constraint is 0 on every row (field P), and every multiplicity is 0/1;
  * BYTES: per id the emitted positions are exactly 0..len-1 (body: 8..|B|-1) and the bytes
    are RC(j) = u64 own ‖ u32 n_j ‖ Σ borsh(receipt), PEO(r), LEAF(r), RID(r), and the body
    B[8..] = Σ borsh(refund);
  * DIGEST receives are sha256 of the emitted bytes with the emitted length;
  * KEYNIB: per walk, exactly the key nibbles ([0]‖receiver, [2]‖signer‖[2]‖pk) and END;
  * FINAL, RCL, RIDS, MPOS as expected; SREC balances inside the table; MEM balances with
    simulated acctV3 open/close messages; AKC with simulated akeyV3, BND with simulated bndV3.
The receipt semantics follow NearSpecV3.applyReceipts (applyReceipt / applySystemReceipt).
"""
