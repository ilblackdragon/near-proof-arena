def ev(e, rows, q, pub, H):
    op, a = e
    if op == 'k': return a[0] % P
    if op == 'c':
        rr = (q + a[1]) % H
        return rows[rr][a[0]] % P
    if op == 'p': return pub[a[0]] % P if a[0] < len(pub) else 0
    if op == 'F': return 1 if q == 0 else 0
    if op == 'L': return 1 if q == H - 1 else 0
    if op == 'T': return 0 if q == H - 1 else 1
    if op == '+': return (ev(a[0], rows, q, pub, H) + ev(a[1], rows, q, pub, H)) % P
    if op == '*':
        x = ev(a[0], rows, q, pub, H)
        return 0 if x == 0 else (x * ev(a[1], rows, q, pub, H)) % P
    if op == '-': return (-ev(a[0], rows, q, pub, H)) % P
    raise Exception(op)

